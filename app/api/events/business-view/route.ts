
import { randomUUID } from "node:crypto";

import { NextRequest, NextResponse } from "next/server";
import { getServerSession } from "next-auth";

import { BusinessStatus, Role } from "@prisma/client";

import { prisma } from "@/lib/prisma";
import { authOptions } from "@/lib/auth";
import { checkPublicRateLimit } from "@/lib/rate-limit";
import { qualifyReferralForUser } from "@/lib/referrals";

const VISITOR_COOKIE_NAME = "remarket_visitor_id";

const VISITOR_COOKIE_MAX_AGE =
  60 * 60 * 24 * 365;

const MAX_BUSINESS_ID_LENGTH = 100;
const MAX_REQUEST_BODY_BYTES = 16 * 1024;

class RequestBodyTooLargeError extends Error {
  constructor() {
    super("Request body is too large.");
    this.name = "RequestBodyTooLargeError";
  }
}

function getResponseHeaders(
  rateLimitHeaders: Headers
): Headers {
  const headers = new Headers(rateLimitHeaders);

  headers.set("Cache-Control", "no-store");
  headers.set("Pragma", "no-cache");

  return headers;
}

function isRecord(
  value: unknown
): value is Record<string, unknown> {
  return (
    typeof value === "object" &&
    value !== null &&
    !Array.isArray(value)
  );
}

function cleanString(value: unknown): string {
  return typeof value === "string"
    ? value.trim()
    : "";
}

/**
 * Read the request body with an actual streaming size limit.
 *
 * This avoids reading an arbitrarily large body into memory
 * before checking its size.
 */
async function readBodyWithLimit(
  request: NextRequest
): Promise<string> {
  const contentLength =
    request.headers.get("content-length");

  if (contentLength) {
    const declaredLength = Number(contentLength);

    if (
      Number.isFinite(declaredLength) &&
      declaredLength > MAX_REQUEST_BODY_BYTES
    ) {
      throw new RequestBodyTooLargeError();
    }
  }

  const reader = request.body?.getReader();

  if (!reader) {
    return "";
  }

  const chunks: Uint8Array[] = [];
  let totalBytes = 0;

  try {
    while (true) {
      const { done, value } = await reader.read();

      if (done) {
        break;
      }

      totalBytes += value.byteLength;

      if (totalBytes > MAX_REQUEST_BODY_BYTES) {
        try {
          await reader.cancel();
        } catch {
          // The request stream may already be closed.
        }

        throw new RequestBodyTooLargeError();
      }

      chunks.push(value);
    }
  } finally {
    reader.releaseLock();
  }

  const bytes = new Uint8Array(totalBytes);

  let offset = 0;

  for (const chunk of chunks) {
    bytes.set(chunk, offset);
    offset += chunk.byteLength;
  }

  return new TextDecoder("utf-8", {
    fatal: true,
  }).decode(bytes);
}

/**
 * Accept only the UUID format generated by randomUUID().
 *
 * Existing invalid or manually modified cookies are replaced.
 */
function isValidVisitorId(
  value: string | undefined
): value is string {
  if (!value || value.length > 100) {
    return false;
  }

  return /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(
    value
  );
}

function attachVisitorCookie(
  response: NextResponse,
  visitorId: string
) {
  response.cookies.set({
    name: VISITOR_COOKIE_NAME,
    value: visitorId,
    httpOnly: true,
    secure: process.env.NODE_ENV === "production",
    sameSite: "lax",
    path: "/",
    maxAge: VISITOR_COOKIE_MAX_AGE,
  });
}

export async function POST(
  request: NextRequest
) {
  /*
   * -----------------------------------------
   * RATE LIMIT
   * -----------------------------------------
   */

  const rateLimit = checkPublicRateLimit(
    request,
    "business-view-event"
  );

  const responseHeaders = () =>
    getResponseHeaders(rateLimit.headers);

  if (!rateLimit.allowed) {
    return NextResponse.json(
      {
        error:
          "Too many view events. Please try again shortly.",
      },
      {
        status: 429,
        headers: responseHeaders(),
      }
    );
  }

  try {
    /*
     * -----------------------------------------
     * READ AND VALIDATE REQUEST BODY
     * -----------------------------------------
     */

    let rawBody: string;

    try {
      rawBody = await readBodyWithLimit(request);
    } catch (bodyError) {
      if (
        bodyError instanceof RequestBodyTooLargeError
      ) {
        return NextResponse.json(
          {
            error: "Request body is too large.",
          },
          {
            status: 413,
            headers: responseHeaders(),
          }
        );
      }

      return NextResponse.json(
        {
          error: "Unable to read request body.",
        },
        {
          status: 400,
          headers: responseHeaders(),
        }
      );
    }

    let body: unknown;

    try {
      body = JSON.parse(rawBody);
    } catch {
      return NextResponse.json(
        {
          error: "Invalid JSON body.",
        },
        {
          status: 400,
          headers: responseHeaders(),
        }
      );
    }

    if (!isRecord(body)) {
      return NextResponse.json(
        {
          error: "Invalid request body.",
        },
        {
          status: 400,
          headers: responseHeaders(),
        }
      );
    }

    /*
     * -----------------------------------------
     * READ BUSINESS ID
     * -----------------------------------------
     *
     * visitorId and userId supplied in the request
     * body are deliberately ignored.
     */

    const businessId = cleanString(body.businessId);

    if (!businessId) {
      return NextResponse.json(
        {
          error: "Business ID is required.",
        },
        {
          status: 400,
          headers: responseHeaders(),
        }
      );
    }

    if (
      businessId.length >
      MAX_BUSINESS_ID_LENGTH
    ) {
      return NextResponse.json(
        {
          error: "Invalid business ID.",
        },
        {
          status: 400,
          headers: responseHeaders(),
        }
      );
    }

    /*
     * -----------------------------------------
     * VERIFY PUBLIC BUSINESS
     * -----------------------------------------
     */

    const business = await prisma.business.findFirst({
      where: {
        id: businessId,
        status: BusinessStatus.ACTIVE,
        deletedAt: null,
      },
      select: {
        id: true,
        ownerId: true,
      },
    });

    if (!business) {
      return NextResponse.json(
        {
          error: "Business not found.",
        },
        {
          status: 404,
          headers: responseHeaders(),
        }
      );
    }

    /*
     * -----------------------------------------
     * RESOLVE AUTHENTICATED USER
     * -----------------------------------------
     *
     * Resolve the current user for ownership checks,
     * regardless of whether the account is a BUYER,
     * SELLER, or ADMIN.
     *
     * Only BUYER accounts are associated with
     * referral-qualifying business views.
     */

    let authenticatedUserId: string | null = null;
    let authenticatedUserRole: Role | null = null;

    try {
      const session = await getServerSession(authOptions);

      const sessionUserId = session?.user?.id;
      const sessionRole = session?.user?.role;

      if (
        typeof sessionUserId === "string" &&
        sessionUserId.trim().length > 0 &&
        typeof sessionRole === "string" &&
        Object.values(Role).includes(sessionRole as Role)
      ) {
        authenticatedUserId = sessionUserId;
        authenticatedUserRole = sessionRole as Role;
      }
    } catch (sessionError) {
      /*
       * Preserve public analytics if session resolution
       * fails. The event will be anonymous and cannot
       * qualify a buyer referral.
       */

      console.error(
        "Business view session resolution error:",
        sessionError
      );
    }

    /*
     * -----------------------------------------
     * EXCLUDE BUSINESS OWNER'S OWN VIEWS
     * -----------------------------------------
     *
     * Check the authenticated ID for every role.
     * Do not count a seller's own profile views.
     */

    if (
      authenticatedUserId &&
      business.ownerId === authenticatedUserId
    ) {
      return NextResponse.json(
        {
          success: true,
          tracked: false,
          reason: "OWNER_VIEW_EXCLUDED",
        },
        {
          status: 200,
          headers: responseHeaders(),
        }
      );
    }

    /*
     * -----------------------------------------
     * RESOLVE VISITOR COOKIE
     * -----------------------------------------
     *
     * Visitor identity is generated by the server.
     * It is not accepted from browser JSON.
     */

    const existingVisitorId =
      request.cookies.get(
        VISITOR_COOKIE_NAME
      )?.value;

    const visitorCookieIsValid =
      isValidVisitorId(existingVisitorId);

    const visitorId = visitorCookieIsValid
      ? existingVisitorId
      : randomUUID();

    const shouldSetVisitorCookie =
      !visitorCookieIsValid;

    /*
     * -----------------------------------------
     * ASSOCIATE AUTHENTICATED BUYER
     * -----------------------------------------
     *
     * Seller and admin views can still count as
     * ordinary anonymous-style traffic for other
     * businesses, but are not used for buyer
     * referral qualification.
     */

    const authenticatedBuyerId =
      authenticatedUserRole === Role.BUYER
        ? authenticatedUserId
        : null;

    /*
     * -----------------------------------------
     * CREATE BUSINESS VIEW EVENT
     * -----------------------------------------
     */

    const event = await prisma.businessViewEvent.create({
      data: {
        businessId,
        visitorId,

        ...(authenticatedBuyerId
          ? {
              userId: authenticatedBuyerId,
            }
          : {}),
      },

      select: {
        id: true,
        businessId: true,
        createdAt: true,
      },
    });

    /*
     * -----------------------------------------
     * CHECK BUYER REFERRAL QUALIFICATION
     * -----------------------------------------
     *
     * The view is saved first.
     * Referral qualification failures must not
     * undo a successfully recorded view.
     */

    if (authenticatedBuyerId) {
      try {
        await qualifyReferralForUser(
          authenticatedBuyerId,
          Role.BUYER
        );
      } catch (qualificationError) {
        console.error(
          "Buyer referral qualification error:",
          qualificationError
        );
      }
    }

    /*
     * -----------------------------------------
     * SUCCESS
     * -----------------------------------------
     */

    const response = NextResponse.json(
      {
        success: true,
        tracked: true,
        event,
      },
      {
        status: 201,
        headers: responseHeaders(),
      }
    );

    if (shouldSetVisitorCookie) {
      attachVisitorCookie(
        response,
        visitorId
      );
    }

    return response;
  } catch (error) {
    console.error(
      "Business view event error:",
      error
    );

    return NextResponse.json(
      {
        error: "Unable to record business view.",
      },
      {
        status: 500,
        headers: responseHeaders(),
      }
    );
  }
}
